"""Turn the results (evals/results.json) into evals/report.md: tables a person can read,
plus every case that didn't meet expectations, so each number can be checked."""

from typing import Any


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0%}"


def num(value: float | None, digits: int = 2) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def ids(values: list[str]) -> str:
    return ", ".join(values) if values else "none"


def render_report(results: dict[str, Any]) -> str:
    run = results.get("run", {})
    lines = [
        "# Evaluation report",
        "",
        "Generated by `uv run servicedesk eval` from "
        "[evals/dataset.jsonl](dataset.jsonl); per-case details are in "
        "[evals/results.json](results.json).",
        "",
        f"- Run: {run.get('date', 'n/a')} · chat model `{run.get('chat_model', 'n/a')}` · "
        f"judge `{run.get('judge_model', 'none')}` · "
        f"embedding `{run.get('embedding_model', 'n/a')}`",
        f"- Dataset: {run.get('questions', 0)} questions "
        f"({run.get('answerable', 0)} answerable, {run.get('out_of_scope', 0)} out of scope), "
        f"{run.get('agent_tasks', 0)} agent tasks",
        "",
    ]
    if "retrieval" in results:
        lines += _retrieval(results["retrieval"]["summary"])
    if "answers" in results:
        lines += _answers(results["answers"])
    if "agent" in results:
        lines += _agent(results["agent"])
    lines += [
        "## How to read this",
        "",
        "- **hit@k**: share of answerable questions with a chunk from an expected document in "
        "the top k results. **MRR**: average of 1/rank of the first such chunk (1.0 = always "
        "first).",
        "- **Grounded**: the judge found every claim of the answer in the sources it cited. "
        "**Correct**: it has the key facts of the hand-written reference answer.",
        "- **Task completion**: the agent called the expected tools, proposed the expected "
        "change (never approved, so nothing was written) and its reply said what it should.",
        f"- Small dataset ({run.get('questions', 0) + run.get('agent_tasks', 0)} cases): one "
        "case moves a rate by several percentage points. The judge is an LLM (see the "
        "limitations in docs/learning-log/phase-8.md).",
        "",
    ]
    return "\n".join(lines)


def _retrieval(summary: dict[str, Any]) -> list[str]:
    k = summary["k"]
    lines = [
        f"## Retrieval ({summary['questions']} answerable questions, top {k})",
        "",
        f"| Mode | hit@1 | hit@3 | hit@{k} | MRR | Missed (not in top {k}) |",
        "|---|---|---|---|---|---|",
    ]
    for mode, m in summary["modes"].items():
        lines.append(
            f"| {mode} | {pct(m['hit@1'])} | {pct(m['hit@3'])} | {pct(m[f'hit@{k}'])} | "
            f"{num(m['mrr'])} | {ids(m['misses'])} |"
        )
    return [*lines, ""]


def _answers(answers: dict[str, Any]) -> list[str]:
    s = answers["summary"]
    lines = [
        f"## Answers ({s['questions']} questions, full RAG pipeline)",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Answered (answerable questions) | {pct(s['answered_when_answerable'])} |",
        f"| Refused (out-of-scope questions) | {pct(s['refused_when_out_of_scope'])} |",
        f"| Cites an expected document | {pct(s['citation_hit_rate'])} |",
        f"| Citation precision (cited docs that are expected) | {pct(s['citation_precision'])} |",
        f"| Grounded (judge: fully supported by its sources) | {pct(s['grounded_rate'])} "
        f"of {s['judged']} |",
        f"| Correct (judge: matches the reference) | {pct(s['correct_rate'])} of {s['judged']} |",
        f"| Latency mean / p95 | {num(s['latency_s_mean'], 1)} s / "
        f"{num(s['latency_s_p95'], 1)} s |",
        f"| Tokens: answers / judge | {s['answer_tokens']:,} / {s['judge_tokens']:,} |",
        "",
        f"- Grounding: {s['grounding'] or 'n/a'}; correctness: {s['correctness'] or 'n/a'}.",
        f"- Refusal reasons: {s['refusal_reasons'] or 'none'}.",
        f"- False refusals: {ids(s['false_refusals'])}. False answers: {ids(s['false_answers'])}. "
        f"Errors: {ids(s['errors'])}.",
        "",
    ]
    flagged = [
        r
        for r in answers["cases"]
        if "judge" in r
        and (r["judge"]["grounding"] != "supported" or r["judge"]["correctness"] != "correct")
    ]
    if flagged:
        lines += ["### Answers the judge flagged", ""]
        for r in flagged:
            j = r["judge"]
            notes = j["unsupported_claims"] + j["missing_points"]
            lines.append(
                f"- **{r['id']}** {r['question']}: {j['grounding']}, {j['correctness']}. "
                f"{j['explanation']}" + (f" ({'; '.join(notes)})" if notes else "")
            )
        lines.append("")
    return lines


def _agent(agent: dict[str, Any]) -> list[str]:
    s = agent["summary"]
    lines = [
        f"## Agent tasks ({s['tasks']} tasks)",
        "",
        f"- **Task completion: {pct(s['task_completion'])}** "
        f"({s['tasks'] - len(s['failed'])}/{s['tasks']}).",
        f"- Latency mean / p95: {num(s['latency_s_mean'], 1)} s / {num(s['latency_s_p95'], 1)} s;"
        f" agent tokens: {s['tokens']:,} (knowledge-base answers not included).",
        "",
        "| Task | Result | Tools called | Proposed change |",
        "|---|---|---|---|",
    ]
    for r in agent["cases"]:
        result = "pass" if r["passed"] else "**fail**: " + "; ".join(r["failures"])
        tools = ", ".join(r.get("tools_called", [])) or "none"
        proposed = ", ".join(a["tool"] for a in r.get("proposed", [])) or "none"
        lines.append(f"| {r['id']} | {result} | {tools} | {proposed} |")
    return [*lines, ""]
